# โฟลเดอร์ฐานของโปรเจกต์ (ที่มี policy.json, secret.env, pass.secret)
BASE_DIR = Path(__file__).resolve().parent.parent.parent
SECRET_ENV_PATH = BASE_DIR / "secret.env"
PASS_SECRET_PATH = BASE_DIR / "pass.secret"
DEVICES_SECRET_PATH = BASE_DIR / "devices.secret"

LOG_DIR = Path("/var/log/tac_plus")


def _read_env(key: str, default: str = "") -> str:
    if not SECRET_ENV_PATH.exists():
        return default
    for line in SECRET_ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(key + "="):
            return line.split("=", 1)[1].strip()
    return default


def load_shared_key() -> str:
    return _read_env("TACACS_SHARED_KEY", "CHANGE_ME") or "CHANGE_ME"


def load_default_user_password() -> str:
    return _read_env("DEFAULT_USER_PASSWORD", "test") or "test"


def load_enable15_password() -> str:
    """
    enable password (ระดับ 15) ที่ OLT จะถามตอนพิมพ์ enable
    ตั้งไว้ใน secret.env เช่น:
      OLT_ENABLE15_PASSWORD=zxr10
    """
    return _read_env("OLT_ENABLE15_PASSWORD", "")


def _escape(s: str) -> str:
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


def _parse_privilege(value) -> int:
    """
    role.privilege ใน policy อาจเป็น '15 / full' หรือ '7' หรือ 7
    """
    # ✅ normalize + clamp 1..15
    return parse_privilege(value, default=1)


def _user_profile_lines(role_name: str, priv: int) -> list[str]:
    role = (role_name or "OLT_VIEW").strip()
    p = max(1, min(15, int(priv)))

    lines: list[str] = []
    lines.append("  profile {")
    lines.append("    script {")

    # Session authorization: set privilege at login
    lines.append("      if (service == exec) {")
    lines.append(f"        set priv-lvl = {p}")
    lines.append("        permit")
    lines.append("      }")

    # Command authorization: requires OLT command-authorization to be enabled
    lines.append("      if (service == shell) {")
    lines.append('        if (cmd == "") permit')

    if role == "OLT_VIEW":
        lines.append(r'        if (cmd =~ /^configure(\s|$)/) deny')

    elif role == "OLT_ENGINEER":
        lines.append(r'        if (cmd =~ /^reload(\s|$)/) deny')

    lines.append("        permit")
    lines.append("      }")
    lines.append("      permit")
    lines.append("    }")
    lines.append("  }")
    return lines


def build_pass_secret_text() -> str:
    """
    สร้าง pass.secret จาก policy.users
    - ใส่ member = <ROLE> เพื่อใช้ ruleset ใน tacacs-generated.cfg map member -> profile
    - ไฟล์นี้เก็บเฉพาะ user/password/member (ไม่ใส่ profile ต่อ user)
    """
    policy = load_policy()
    users = policy.get("users", [])

    default_pw = load_default_user_password()

    lines: list[str] = []
    lines.append("# Auto-generated by NT TACACS+ Dashboard")
    lines.append("# ห้ามแก้ไฟล์นี้ตรง ๆ (จะแทนที่ทุกครั้งที่ generate จาก web)")
    lines.append("")

    for u in users:
        username = (u.get("username") or u.get("name") or "").strip()
        if not username:
            continue

        status = (u.get("status") or "Active").strip().lower()
        if status not in ("active", "enable", "enabled"):
            continue

        role = (
            u.get("roles")
            or u.get("role")
            or u.get("group")
            or u.get("role_name")
            or u.get("roleName")
            or "OLT_VIEW"
        )
        role = str(role).strip() or "OLT_VIEW"

        # ✅ ensure มี entry ใน user_secrets.json (ถ้ายังไม่มีก็ใส่ default ให้)
        ensure_user_has_password(username)

        # ✅ password ของ user (ถ้าไม่มีราย user จะ fallback ไป default_password)
        pw = get_user_password(username) or default_pw

        lines.append(f"user {username} {{")
        lines.append(f'  password login = clear "{_escape(pw)}"')
        lines.append("  password pap = login")
        lines.append(f"  member = {role}")
        lines.append("}")
        lines.append("")

    return "\n".join(lines)

def _role_profile_block_lines(role_name: str, priv: int) -> list[str]:
    """สร้าง profile block สำหรับ role หนึ่ง ๆ (ใส่ใน tacacs-generated.cfg)"""
    role = (role_name or "OLT_VIEW").strip() or "OLT_VIEW"
    p = max(1, min(15, int(priv)))

    lines: list[str] = []
    lines.append(f"  profile = {role} {{")
    lines.append("    script {")
    lines.append("      if (service == exec) {")
    lines.append(f"        set priv-lvl = {p}")
    lines.append("        permit")
    lines.append("      }")
    lines.append("      if (service == shell) {")
    lines.append('        if (cmd == "") permit')
    if role == "OLT_VIEW":
        lines.append(r'        if (cmd =~ /^configure(\s|$)/) deny')
    elif role == "OLT_ENGINEER":
        lines.append(r'        if (cmd =~ /^reload(\s|$)/) deny')
    lines.append("        permit")
    lines.append("      }")
    lines.append("      permit")
    lines.append("    }")
    lines.append("  }")
    return lines


def build_devices_secret_text() -> str:
    """สร้าง devices.secret จาก policy.devices (host blocks)

    ไฟล์นี้จะถูก include จาก tacacs-generated.cfg เพื่อแยกส่วน device ออกจากไฟล์หลัก
    และเก็บ key ไว้ในไฟล์สิทธิ์ 600 เช่นเดียวกับ pass.secret
    """
    policy = load_policy()
    devices = policy.get("devices", [])
    shared_key = load_shared_key()

    lines: list[str] = []
    lines.append("# Auto-generated by NT TACACS+ Dashboard")
    lines.append("# Devices/hosts are generated here (included by tacacs-generated.cfg)")
    lines.append("")

    for dev in devices:
        name = dev.get("name") or dev.get("id") or "OLT_UNKNOWN"
        addr = dev.get("address") or dev.get("ip") or "0.0.0.0"
        lines.append(f"  host = {name} {{")
        lines.append(f"    address = {addr}")
        lines.append(f'    key = "{_escape(shared_key)}"')
        lines.append("  }")
        lines.append("")

    return "\n".join(lines)


def build_config_text() -> str:
    """สร้าง tacacs-generated.cfg (profiles + ruleset อยู่ในไฟล์นี้)"""
    policy = load_policy()
    roles = policy.get("roles", [])

    role_priv = {(r.get("name") or "").strip(): _parse_privilege(r.get("privilege")) for r in roles}

    lines: list[str] = []
    lines.append("# Auto-generated by NT TACACS+ Dashboard")
    lines.append("# ห้ามแก้ไฟล์นี้ตรง ๆ (จะแทนที่ทุกครั้งที่ generate จาก web)")
    lines.append("")

    # spawnd
    lines.append("id = spawnd {")
    lines.append("  listen = {")
    lines.append("    port = 49")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    # tac_plus-ng
    lines.append("id = tac_plus-ng {")
    lines.append("  # ----- Logging (authc/authz/acct/conn) -----")
    lines.append(f"  log authclog {{ destination = {LOG_DIR}/authc-%Y-%m-%d.log }}")
    lines.append(f"  log authzlog {{ destination = {LOG_DIR}/authz-%Y-%m-%d.log }}")
    lines.append(f"  log acctlog  {{ destination = {LOG_DIR}/acct-%Y-%m-%d.log }}")
    lines.append("")
    lines.append("  authentication log = authclog")
    lines.append("  authorization log = authzlog")
    lines.append("  accounting log = acctlog")
    lines.append("")

    # Devices (hosts)
    lines.append("  # ----- Devices (hosts) in separate devices.secret file -----")
    lines.append(f'  include = "{DEVICES_SECRET_PATH}"')
    lines.append("")

    # Roles -> group
    lines.append("  # ----- Roles (as groups) -----")
    for r in roles:
        name = (r.get("name") or "").strip()
        if not name:
            continue
        lines.append(f"  group = {name} {{")
        lines.append("  }")
        lines.append("")
    if not roles:
        for name in ("OLT_VIEW", "OLT_ENGINEER", "OLT_ADMIN"):
            lines.append(f"  group = {name} {{")
            lines.append("  }")
            lines.append("")

    # Profiles
    lines.append("  # ----- Profiles (RBAC scripts) -----")
    preferred = ["OLT_VIEW", "OLT_ENGINEER", "OLT_ADMIN"]
    role_names = [str((r.get("name") or "")).strip() for r in roles]
    role_names = [n for n in role_names if n]
    ordered: list[str] = []
    for n in preferred:
        if n in role_names:
            ordered.append(n)
    for n in role_names:
        if n not in ordered:
            ordered.append(n)
    if not ordered:
        ordered = preferred

    for name in ordered:
        priv = role_priv.get(name, 1)
        lines.extend(_role_profile_block_lines(name, priv))
        lines.append("")

    # Ruleset: member -> profile
    lines.append("  # ----- Ruleset: member -> profile -----")
    lines.append("  ruleset {")
    lines.append("    rule {")
    lines.append("      enabled = yes")
    lines.append("      script {")
    for name in ordered:
        lines.append(f"        if (member == {name}) {{ profile = {name} permit }}")
    lines.append("       deny ")
    lines.append("      }")
    lines.append("    }")
    lines.append("  }")
    lines.append("")

    # include pass.secret
    lines.append("  # Users are defined in separate pass.secret file")
    lines.append(f'  include = "{PASS_SECRET_PATH}"')
    lines.append("}")

    return "\n".join(lines)


